import { readFile } from "node:fs/promises";
import { join, resolve } from "node:path";

export interface LockSource {
  id: string;
  name: string;
  repo: string;
  commit: string;
  license: string;
  licenseUrl: string;
  authors: string[];
  url: string;
  notes: string;
  paths: Record<string, string>;
}

export interface SourceLock {
  version: number;
  generatedAt: string;
  sources: LockSource[];
}

async function readLock(path: string): Promise<SourceLock> {
  let raw: string;
  try {
    raw = await readFile(path, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") throw error;
    throw new Error(
      `Cannot read ${path}: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    throw new Error(
      `Invalid JSON in ${path}: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
  const lock = parsed as Partial<SourceLock>;
  if (!lock || !Array.isArray(lock.sources)) {
    throw new Error(`Invalid source lock at ${path}: expected a sources array`);
  }
  return lock as SourceLock;
}

/**
 * The repository-root lock is the human-edited source of truth. The packaged
 * copy is generated by ingest and is only a fallback for installed packages.
 */
export async function loadSourceLock(
  contentDir: string,
  rootDir = resolve(contentDir, ".."),
): Promise<SourceLock> {
  const candidates = [join(rootDir, "sources.lock.json"), join(contentDir, "sources.lock.json")];
  for (const candidate of candidates) {
    try {
      return await readLock(candidate);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") continue;
      throw error;
    }
  }
  throw new Error(`sources.lock.json not found in ${candidates.join(" or ")}`);
}

/** Cache paths include the pinned commit so a new pin can never reuse old bytes. */
export function sourceCacheKey(source: Pick<LockSource, "id" | "commit">, path: string): string {
  return `${source.id}/${source.commit}/${path.replace(/^\/+/, "")}`;
}
